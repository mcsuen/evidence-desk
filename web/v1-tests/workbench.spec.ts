test('source correction creates new input, continues research and adopts an exact judgment revision',async({page})=>{
 await page.goto('/companies/PDD')
 await page.getByRole('link',{name:'资料',exact:true}).click()
 const original=page.getByRole('heading',{name:'离线界面测试原件',exact:true}).locator('..')
 await original.getByText('来源更正或撤回',{exact:true}).click()
 await original.getByLabel('撤回原因').fill('验收：原公司披露需要更正')
 await original.getByRole('button',{name:'撤回此版本',exact:true}).click()
 await page.locator('input[type=file]').setInputFiles({name:'更正后的原件.txt',mimeType:'text/plain',buffer:Buffer.from('PDD Holdings 2025Q2 GAAP RMB millions. Revenue 120.000')})
 await expect(page.getByRole('heading',{name:'更正后的原件.txt',exact:true})).toBeVisible()
 await page.goto('/research')
 await page.getByRole('link',{name:'离线界面验收：季度研究'}).click()
 await expect(page.getByText(/当前有效性提示/)).toBeVisible()
 await page.getByRole('button',{name:'补充材料与问题',exact:true}).click()
 await page.getByLabel('补充后的研究问题').fill('来源更正后继续研究')
 await page.getByRole('button',{name:'移除此旧版本'}).click()
 await page.getByLabel('更正后的原件.txt · 修订 1').check()
 await page.getByRole('button',{name:'保存新输入修订'}).click()
 await expect(page.getByText('输入修订 2',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'从当前输入研究',exact:true}).click()
 await expect(page.getByRole('heading',{name:'来源更正后的报告',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'查看数值依据：120.000 百万元人民币'})).toBeVisible()
 await page.goto('/review')
 await page.getByLabel('决定理由：收入规模').fill('验收：核对更正后的原件')
 await page.getByRole('button',{name:'采纳判断',exact:true}).click()
 await page.goto('/companies/PDD/knowledge')
 await page.getByRole('link',{name:/收入规模/}).first().click()
 await expect(page.getByText('更正后原件对应的季度收入',{exact:true})).toBeVisible()
 await expect(page.getByText('修订 2',{exact:true})).toBeVisible()
})

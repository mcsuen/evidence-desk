import {test,expect} from '@playwright/test'

test('typed evidence, focus, revisions, independent Word retry and history',async({page})=>{
 await page.goto('/research')
 await page.getByRole('link',{name:'离线界面验收：季度研究'}).click()
 const chip=page.getByRole('button',{name:/查看数值依据/}).first()
 await chip.click()
 await expect(page.getByTestId('evidence-rail')).toContainText('Revenue 100.000')
 await page.keyboard.press('Escape')
 await expect(chip).toBeFocused()
 await page.getByRole('button',{name:'修订报告',exact:true}).click()
 await page.getByLabel('报告标题',{exact:true}).fill('修订后的离线报告')
 await page.getByLabel('修订原因',{exact:true}).fill('明确表述')
 await page.getByRole('button',{name:'保存新修订并重新核验'}).click()
 await expect(page.getByRole('heading',{name:'修订后的离线报告',exact:true})).toBeVisible()
 await expect(page.getByLabel('报告版本')).toHaveValue('2')
 const before=await (await page.request.get('/api/v1/runs')).json()
 await page.getByRole('button',{name:'导出 Word',exact:true}).click()
 await page.getByRole('button',{name:'仅重试导出',exact:true}).click()
 await expect(page.getByRole('link',{name:'下载 Word',exact:true})).toBeVisible({timeout:40000})
 const download=page.waitForEvent('download');await page.getByRole('link',{name:'下载 Word',exact:true}).click();expect((await download).suggestedFilename()).toContain('.docx')
 expect((await (await page.request.get('/api/v1/runs')).json()).map((r:any)=>r.id)).toEqual(before.map((r:any)=>r.id))
 await page.getByRole('button',{name:/查看数值依据/}).first().click()
 await expect(page.getByTestId('evidence-rail')).toBeVisible()
 await page.getByLabel('报告版本').selectOption('1')
 await expect(page.getByTestId('evidence-rail')).toHaveCount(0)
 await expect(page.getByRole('heading',{name:'拼多多季度研究',exact:true})).toBeVisible()
 await expect(page.getByRole('link',{name:'下载 Word',exact:true})).toHaveCount(0)
 const trace=await(await page.request.get('/api/v1/runs/'+before[0].id+'/trace')).json()
 expect(trace.spans.filter((s:any)=>s.kind==='export').map((s:any)=>s.status)).toEqual(['failed','completed'])
 await page.getByRole('radio',{name:'执行流程',exact:true}).click()
 await expect(page.getByTestId('run-graph')).toContainText('生成 Word')
})

